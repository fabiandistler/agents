"""The handoff protocol module: marker text, round trip, authorship and malformed markers."""

from __future__ import annotations

import pytest
from factory_handoff import (
    APP_LOGIN,
    REWORK_HANDOFF,
    REWORK_ROUND,
    WORKFLOW_BOT_LOGIN,
    format_marker,
    read_markers,
)

HEAD = "0123456789abcdef0123456789abcdef01234567"
OTHER_HEAD = "f" * 40
KINDS = {
    "round": (REWORK_ROUND, {"round": 2, "head": HEAD}),
    "handoff": (REWORK_HANDOFF, {"head": HEAD}),
}


def entry(body: object, author: object = WORKFLOW_BOT_LOGIN) -> dict:
    return {"id": 1, "body": body, "author": author}


def fields_read(kind, entries) -> list[dict]:
    return [fields for read in read_markers(kind, entries) for fields in read.markers]


def test_the_logins():
    assert WORKFLOW_BOT_LOGIN == "github-actions[bot]"
    assert APP_LOGIN == "claude[bot]"


def test_the_rework_round_text_is_as_stored_on_github():
    assert format_marker(REWORK_ROUND, round=2, head=HEAD) == f"<!-- rework-round:2 head:{HEAD} -->"


def test_the_rework_handoff_text_is_as_stored_on_github():
    assert format_marker(REWORK_HANDOFF, head=HEAD) == f"<!-- rework-handoff head:{HEAD} -->"


@pytest.mark.parametrize("name", KINDS)
def test_format_then_read_round_trips(name):
    kind, fields = KINDS[name]
    body = f"{format_marker(kind, **fields)}\n> *This was generated by AI.*"
    reads = read_markers(kind, [entry(body)])
    assert [(read.entry["body"], read.markers) for read in reads] == [(body, (fields,))]


@pytest.mark.parametrize("name", KINDS)
@pytest.mark.parametrize("author", ["fabiandistler", APP_LOGIN, "", None])
def test_a_marker_by_anyone_but_the_workflow_bot_reads_as_nothing(name, author):
    kind, fields = KINDS[name]
    assert read_markers(kind, [entry(format_marker(kind, **fields), author)]) == []


@pytest.mark.parametrize("name", KINDS)
def test_an_entry_without_an_author_reads_as_nothing(name):
    kind, fields = KINDS[name]
    assert read_markers(kind, [{"body": format_marker(kind, **fields)}]) == []


@pytest.mark.parametrize(
    "body",
    [
        f"<!-- rework-round:0 head:{HEAD} -->",
        f"<!-- rework-round:01 head:{HEAD} -->",
        f"<!-- rework-round:1 head:{HEAD[:39]} -->",
        f"<!-- rework-round:1 head:{HEAD.upper()} -->",
        "<!-- rework-round:1 -->",
        f"<!-- rework-handoff head:{HEAD} -->",
    ],
)
def test_a_malformed_round_marker_reads_as_nothing(body):
    assert read_markers(REWORK_ROUND, [entry(body)]) == []


@pytest.mark.parametrize(
    "body",
    [
        f"<!-- rework-handoff head:{HEAD[:39]} -->",
        f"<!-- rework-handoff head:{HEAD.upper()} -->",
        "<!-- rework-handoff head: -->",
        f"<!-- rework-round:1 head:{HEAD} -->",
    ],
)
def test_a_malformed_handoff_marker_reads_as_nothing(body):
    assert read_markers(REWORK_HANDOFF, [entry(body)]) == []


@pytest.mark.parametrize("name", KINDS)
@pytest.mark.parametrize("body", [None, 7, ["x"]])
def test_an_entry_without_a_string_body_is_skipped(name, body):
    kind, fields = KINDS[name]
    good = entry(format_marker(kind, **fields))
    assert fields_read(kind, [entry(body), "not a mapping", good]) == [fields]


def test_entry_order_and_every_marker_in_a_body_are_kept():
    first = entry(
        format_marker(REWORK_ROUND, round=1, head=OTHER_HEAD)
        + format_marker(REWORK_ROUND, round=2, head=HEAD)
    )
    second = entry(format_marker(REWORK_ROUND, round=3, head=OTHER_HEAD))
    reads = read_markers(REWORK_ROUND, [first, entry("no marker"), second])
    assert [read.entry for read in reads] == [first, second]
    assert fields_read(REWORK_ROUND, [first, second]) == [
        {"round": 1, "head": OTHER_HEAD},
        {"round": 2, "head": HEAD},
        {"round": 3, "head": OTHER_HEAD},
    ]


@pytest.mark.parametrize(
    "fields",
    [
        {"round": 0, "head": HEAD},
        {"round": -1, "head": HEAD},
        {"round": True, "head": HEAD},
        {"round": "1", "head": HEAD},
        {"round": 1, "head": HEAD[:39]},
        {"round": 1, "head": HEAD.upper()},
        {"round": 1, "head": ""},
        {"round": 1},
        {"round": 1, "head": HEAD, "extra": 1},
    ],
)
def test_the_round_formatter_rejects_invalid_fields(fields):
    with pytest.raises(ValueError):
        format_marker(REWORK_ROUND, **fields)


@pytest.mark.parametrize(
    "fields", [{"head": ""}, {"head": None}, {"head": HEAD.upper()}, {}, {"head": HEAD, "round": 1}]
)
def test_the_handoff_formatter_rejects_invalid_fields(fields):
    with pytest.raises(ValueError):
        format_marker(REWORK_HANDOFF, **fields)
