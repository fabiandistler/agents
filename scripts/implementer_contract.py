"""Whose text on an issue is the implementer's contract.

Anyone can write on a public issue, and the model that reads the contract holds
a write token. So only text by the repository's owner, members and
collaborators can be the contract: the latest comment by one of them that
contains a `## Agent Brief` heading, or without one a trusted author's issue
body and the trusted comments. Text by anyone else stays data. What counts as
a brief and as a trusted author is in ``agent_brief.py``.

Standard library only. Errors name the API call, never issue text.
"""

from __future__ import annotations

from dataclasses import dataclass

from agent_brief import is_agent_brief, is_trusted
from pr_github_client import FetchError, ReadClient, get_json, paginate

NO_CONTRACT_COMMENT = """\
> *This was generated by AI.*

The implementer did not start: this issue has no contract written by someone \
with write access to the repository. The issue was opened by an account \
without write access, and no such person has posted a comment containing a \
`## Agent Brief` heading. Post that comment with what to build, then add \
`ready-for-agent` again: no run starts on its own.
"""


@dataclass(frozen=True)
class Ticket:
    """The issue's texts, split by whether their author has write access."""

    body: str
    body_is_trusted: bool
    brief: str | None
    trusted_comments: tuple[str, ...]


def read_ticket(client: ReadClient, repo: str, issue: int) -> Ticket:
    """The issue body, the latest trusted Agent Brief and the other trusted comments."""
    issue_path = f"/repos/{repo}/issues/{issue}"
    ticket = get_json(client, issue_path)
    if not isinstance(ticket, dict) or "body" not in ticket:
        raise FetchError(f"GitHub API returned a malformed issue for {issue_path}")
    # GitHub sends a null body for an issue without a description.
    body = ticket["body"] or ""
    if not isinstance(body, str):
        raise FetchError(f"GitHub API returned a malformed issue for {issue_path}")
    briefs: list[str] = []
    trusted_comments: list[str] = []
    for comment in paginate(client, f"{issue_path}/comments"):
        text = comment.get("body") if isinstance(comment, dict) else None
        if not isinstance(text, str):
            raise FetchError(f"GitHub API returned a malformed comment for {issue_path}")
        if not is_trusted(comment):
            continue
        if is_agent_brief(text):
            briefs.append(text)
        else:
            trusted_comments.append(text)
    brief = briefs[-1] if briefs else None
    return Ticket(body, is_trusted(ticket), brief, tuple(trusted_comments))


def contract_text(ticket: Ticket, issue: int) -> str | None:
    """The latest trusted brief; without one, a trusted author's body and the trusted comments."""
    if ticket.brief is not None:
        source = "the latest Agent Brief comment by a person with write access"
        parts = [ticket.brief]
    elif ticket.body_is_trusted:
        source = "the issue body and the comments by people with write access"
        parts = [ticket.body, *ticket.trusted_comments]
    else:
        return None
    header = f"Contract for issue #{issue}. Source: {source}."
    return "\n\n---\n\n".join([header, *parts]) + "\n"
