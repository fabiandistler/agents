"""Whose text on an issue is the implementer's contract.

Anyone can write on a public issue, and the model that reads the contract holds
a write token. So only text by the repository's owner, members and
collaborators can be the contract: the latest comment by one of them that
contains a `## Agent Brief` heading, or without one a trusted body and the
trusted comments. Text by anyone else stays data. What counts as a brief and as
a trusted author is in ``agent_brief.py``.

A body is trusted when its author is, or when it is an audit finding a person
released: an issue the Claude GitHub App opened under the `audit-finding`
label, whose latest `ready-for-agent` label a person with write access added,
and whose body still hashes to the release marker the workflow bot posted after
that label. The audit that files it already writes pull requests with the same
App token, so trusting its issue grants it nothing new; the person's label is
the gate, and the marker pins the text they released (ADR-0020).

Standard library only. Errors name the API call, never issue text.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass

from agent_brief import is_agent_brief, is_trusted
from factory_handoff import (
    APP_LOGIN,
    AUDIT_FINDING,
    AUDIT_RELEASE,
    READY_FOR_AGENT,
    format_marker,
    read_markers,
)
from pr_github_client import HTTP_NOT_FOUND, FetchError, ReadClient, get_json, paginate

NO_CONTRACT_COMMENT = """\
> *This was generated by AI.*

The implementer did not start: this issue has no contract written by someone \
with write access to the repository. The issue was opened by an account \
without write access, and no such person has posted a comment containing a \
`## Agent Brief` heading. Post that comment with what to build, then add \
`ready-for-agent` again: no run starts on its own.
"""


@dataclass(frozen=True)
class Ticket:
    """The issue's texts, split by whether their author has write access."""

    body: str
    body_is_trusted: bool
    brief: str | None
    trusted_comments: tuple[str, ...]


def read_ticket(client: ReadClient, repo: str, issue: int) -> Ticket:
    """The issue body, the latest trusted Agent Brief and the other trusted comments."""
    issue_path = f"/repos/{repo}/issues/{issue}"
    ticket = get_json(client, issue_path)
    if not isinstance(ticket, dict) or "body" not in ticket:
        raise FetchError(f"GitHub API returned a malformed issue for {issue_path}")
    # GitHub sends a null body for an issue without a description.
    body = ticket["body"] or ""
    if not isinstance(body, str):
        raise FetchError(f"GitHub API returned a malformed issue for {issue_path}")
    briefs: list[str] = []
    trusted_comments: list[str] = []
    for comment in paginate(client, f"{issue_path}/comments"):
        text = comment.get("body") if isinstance(comment, dict) else None
        if not isinstance(text, str):
            raise FetchError(f"GitHub API returned a malformed comment for {issue_path}")
        if not is_trusted(comment):
            continue
        if is_agent_brief(text):
            briefs.append(text)
        else:
            trusted_comments.append(text)
    brief = briefs[-1] if briefs else None
    return Ticket(
        body, body_is_trusted(client, repo, issue, ticket), brief, tuple(trusted_comments)
    )


def body_is_trusted(client: ReadClient, repo: str, number: int, issue: dict) -> bool:
    """Whether the issue body may be a contract: a trusted author's, or a released audit finding."""
    if is_trusted(issue):
        return True
    if not is_audit_finding(issue):
        return False
    release = person_release(client, repo, number)
    if release is None:
        return False
    return is_pinned_since(latest_release_pin(client, repo, number), issue, release)


def is_audit_finding(issue: dict) -> bool:
    """Whether the Claude GitHub App opened ``issue`` under the `audit-finding` label."""
    user = issue.get("user")
    labels = issue.get("labels")
    if not isinstance(user, dict) or not isinstance(labels, list):
        return False
    names = {label.get("name") for label in labels if isinstance(label, dict)}
    return user.get("login") == APP_LOGIN and user.get("type") == "Bot" and AUDIT_FINDING in names


# The base roles the permission endpoint reports for write access; it maps
# maintain to write and triage to read.
WRITE_PERMISSIONS = frozenset({"admin", "write"})


def person_release(client: ReadClient, repo: str, number: int) -> dict | None:
    """The latest `ready-for-agent` label event, when a person with write access added it.

    The App can label its own issue too, and the implementer queue dispatches
    any labelled issue, so without this check nobody would stand between an
    audit run and an implementer run. A label event carries no author
    association, so the adder's permission is asked for separately.
    """
    path = f"/repos/{repo}/issues/{number}/events"
    releases = [event for event in paginate(client, path) if _adds_ready_label(event)]
    if not releases:
        return None
    actor = releases[-1].get("actor")
    if not isinstance(actor, dict) or actor.get("type") != "User":
        return None
    login = actor.get("login")
    if not (isinstance(login, str) and _has_write_access(client, repo, login)):
        return None
    return releases[-1]


def body_hash(issue: dict) -> str:
    """The SHA-256 of the issue body as the API sends it; a null body hashes as empty."""
    body = issue.get("body") or ""
    if not isinstance(body, str):
        raise FetchError("GitHub API returned a malformed issue body")
    return hashlib.sha256(body.encode("utf-8")).hexdigest()


def release_marker(issue: dict) -> str:
    """The audit release marker that pins ``issue``'s current body."""
    return format_marker(AUDIT_RELEASE, sha256=body_hash(issue))


def latest_release_pin(client: ReadClient, repo: str, number: int) -> tuple[str, str] | None:
    """The hash and creation time of the workflow bot's latest audit release marker.

    The App can comment too, so ``read_markers`` counts only the workflow
    bot's comments; a marker a person or the App quotes is just text.
    """
    path = f"/repos/{repo}/issues/{number}/comments"
    entries = [_marker_entry(comment) for comment in paginate(client, path)]
    pins = [
        (str(marker["sha256"]), str(read.entry["created_at"]))
        for read in read_markers(AUDIT_RELEASE, entries)
        for marker in read.markers
    ]
    return pins[-1] if pins else None


def _marker_entry(comment: dict) -> dict:
    user = comment.get("user")
    login = user.get("login") if isinstance(user, dict) else None
    created_at = comment.get("created_at")
    return {
        "author": login if isinstance(login, str) else "",
        "body": comment.get("body"),
        "created_at": created_at if isinstance(created_at, str) else "",
    }


def is_pinned_since(pin: tuple[str, str] | None, issue: dict, release: dict) -> bool:
    """Whether ``pin`` holds ``issue``'s current body hash and was posted at or after ``release``.

    The REST API keeps no body-edit time, so the release marker stands in for
    it: a body the App changed after the release no longer matches. GitHub
    writes both times as UTC ISO 8601 with a ``Z``, so they compare as text.
    """
    if pin is None:
        return False
    pinned_hash, pinned_at = pin
    released_at = release.get("created_at")
    if not isinstance(released_at, str) or not released_at or not pinned_at:
        return False
    return pinned_at >= released_at and pinned_hash == body_hash(issue)


def _adds_ready_label(event: dict) -> bool:
    label = event.get("label")
    return (
        event.get("event") == "labeled"
        and isinstance(label, dict)
        and label.get("name") == READY_FOR_AGENT
    )


def _has_write_access(client: ReadClient, repo: str, login: str) -> bool:
    """Whether ``login`` can write to ``repo``; a 404 (no such user) means no."""
    path = f"/repos/{repo}/collaborators/{login}/permission"
    try:
        answer = get_json(client, path)
    except FetchError as error:
        if error.status == HTTP_NOT_FOUND:
            return False
        raise
    if not isinstance(answer, dict):
        raise FetchError(f"GitHub API returned a malformed permission for {path}")
    return answer.get("permission") in WRITE_PERMISSIONS


def contract_text(ticket: Ticket, issue: int) -> str | None:
    """The latest trusted brief; without one, a trusted author's body and the trusted comments."""
    if ticket.brief is not None:
        source = "the latest Agent Brief comment by a person with write access"
        parts = [ticket.brief]
    elif ticket.body_is_trusted:
        source = "the issue body and the comments by people with write access"
        parts = [ticket.body, *ticket.trusted_comments]
    else:
        return None
    header = f"Contract for issue #{issue}. Source: {source}."
    return "\n\n---\n\n".join([header, *parts]) + "\n"
