#!/usr/bin/env python3
"""Claim one issue's branch for an implementer run, or say why the run must stop.

factory-implementer.yml's model runs this as its first write, with the App token it
already holds: no step before the model step has a token that can create a
ref. Creating the branch is the atomic claim. A branch that already exists is
recovered, kept for the pull request that holds it, or handed to a person.

Runs for one issue are serialised by the job's concurrency group, so an
existing branch never belongs to a live run of this workflow.

Before any branch exists, three intake gates can stop the run: a ticket with no
contract written by a person with write access, a ticket whose blockers are not
done, and a run while another one is working. Each comments. A ticket with no
contract loses `ready-for-agent`, because only a person's brief can restart it.
A blocked ticket and one stopped at capacity keep the label and wait in the
queue --queue-workflow names, checked only then to be an active workflow of the
repository; with an empty --queue-workflow they lose it too
(implementer_waiting.py).

The contract is what the run builds; implementer_contract.py decides whose text
it is. The script writes it to --contract, so the run works from a file fixed
at claim time.
The capacity gate reads the Actions API with the job token (ACTIONS_READ_TOKEN),
because the App token cannot be shown to have Actions read (ADR-0014).
--workflow-file, --job-name and --branch-prefix let a run called as a reusable
workflow from another repository find its runs and name its branch
(implementer_setup.py).

Standard library only. Prints one JSON object; errors name the API call and
status, never issue or pull request text.
"""

