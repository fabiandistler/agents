#!/usr/bin/env python3
"""Claim one issue's branch for an implementer run, or say why the run must stop.

implementer.yml's model runs this as its first write, with the App token it
already holds: no step before the model step has a token that can create a
ref. Creating the branch is the atomic claim. A branch that already exists is
recovered, kept for the pull request that holds it, or handed to a person.

Runs for one issue are serialised by the job's concurrency group, so an
existing branch never belongs to a live run of this workflow.

Before any branch exists, two intake gates can stop the run: a ticket whose
blockers are not done, and a run while another one is working. Both comment and
remove `ready-for-agent`; a person adds it again, which is the only restart.
The capacity gate reads the Actions API with the job token (ACTIONS_READ_TOKEN),
because the App token cannot be shown to have Actions read (ADR-0014).

Standard library only. Prints one JSON object; errors name the API call and
status, never issue or pull request text.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from dataclasses import asdict, dataclass
from datetime import datetime
from pathlib import Path

from agent_run_report import FAILED_PREFIX
from check_pr_issue_links import closing_references
from issue_triage_policy import READY_FOR_AGENT, READY_FOR_HUMAN
from pr_github import PER_PAGE, get_json, paginate
from pr_github_client import REPO_PATTERN, FetchError, GitHubClient, MissingTokenError, ReadClient
from ticket_blockers import declared_blockers

MAIN_BRANCH = "main"
HTTP_NOT_FOUND = 404
HTTP_GONE = 410
HTTP_UNPROCESSABLE = 422

ACTIONS_TOKEN_VARIABLE = "ACTIONS_READ_TOKEN"  # noqa: S105 -- a variable name, not a value.
IMPLEMENTER_WORKFLOW = "implementer.yml"
IMPLEMENT_JOB = "implement"
MAX_WORKING_RUNS = 1
AGENT_BRIEF_PREFIX = "## Agent Brief"

CLAIMED = "claimed"
RECLAIMED = "reclaimed"
PR_EXISTS = "pr-exists"
NEEDS_HUMAN = "needs-human"
BLOCKED = "blocked"
AT_CAPACITY = "at-capacity"
FAILED = "failed"

EXIT_CONTINUE = 0
EXIT_FAILED = 1
EXIT_USAGE = 2
EXIT_PR_EXISTS = 3
EXIT_NEEDS_HUMAN = 4
EXIT_BLOCKED = 5
EXIT_AT_CAPACITY = 6
EXIT_CODES = {
    CLAIMED: EXIT_CONTINUE,
    RECLAIMED: EXIT_CONTINUE,
    PR_EXISTS: EXIT_PR_EXISTS,
    NEEDS_HUMAN: EXIT_NEEDS_HUMAN,
    BLOCKED: EXIT_BLOCKED,
    AT_CAPACITY: EXIT_AT_CAPACITY,
}

HANDOFF_COMMENT = """\
> *This was generated by AI.*

The implementer did not start: branch `{branch}` has commits that are not on \
`main`, and no open pull request uses it. A run crashed after pushing, or a \
pull request from it was closed without merging. An implementer run never \
builds on such a branch, so this issue now waits for a person.

To continue the work, open a pull request from the branch. To start over, \
rescue what you need, delete the branch, and add `ready-for-agent` again.
"""

BLOCKED_COMMENT = """\
> *This was generated by AI.*

The implementer did not start. {reason}

A blocker counts as done only when it is closed as completed; closed as not \
planned still blocks. When every blocker is done, add `ready-for-agent` again: \
no run starts on its own.
"""

CAPACITY_COMMENT = f"""\
> *This was generated by AI.*

The implementer did not start: another implementer run is working, and at most \
{MAX_WORKING_RUNS} may work at a time. Add `ready-for-agent` again when that run \
has ended: no run starts on its own.
"""

HELP_EPILOG = """\
stdout: JSON with outcome, branch, pull_request, blockers, unresolved_blockers ("reason" if failed).
outcomes and exit codes:
  0 claimed      branch created at main
  0 reclaimed    branch existed with no commits of its own; moved to main
  3 pr-exists    an open or merged PR closes the issue, or an open PR uses the branch
  4 needs-human  branch has commits and no open PR; commented and set ready-for-human
  5 blocked      a declared blocker is not closed as completed; commented, removed the label
  6 at-capacity  another implementer run is working; commented, removed the label
  1 failed       any other API error; wrote "RUN FAILED: claim (<reason>)" to --summary
  2              usage error
env: GH_TOKEN (the App token inside claude-code-action), ACTIONS_READ_TOKEN, GITHUB_RUN_ID.

examples:
  implementer_claim.py --repo owner/repo --issue 42 --summary "$RUNNER_TEMP/run-summary.md"
  implementer_claim.py --help
"""


@dataclass(frozen=True)
class ClaimOutcome:
    outcome: str
    branch: str
    pull_request: int | None = None
    blockers: tuple[int, ...] = ()
    unresolved_blockers: int = 0


def _read_ref_sha(client: GitHubClient, repo: str, branch: str) -> str:
    path = f"/repos/{repo}/git/ref/heads/{branch}"
    ref = get_json(client, path)
    try:
        sha = ref["object"]["sha"]
    except (KeyError, TypeError) as error:
        raise FetchError(f"GitHub API returned a malformed ref for {path}") from error
    if not isinstance(sha, str) or not sha:
        raise FetchError(f"GitHub API returned a malformed ref for {path}")
    return sha


def _pull_request_holding_issue(
    client: GitHubClient, repo: str, issue: int, branch: str
) -> int | None:
    """The first open or merged PR that closes the issue, or an open PR on its branch."""
    path = f"/repos/{repo}/pulls"
    issue_reference = f"{repo.lower()}#{issue}"
    head_label = f"{repo.split('/')[0]}:{branch}"
    for pull in paginate(client, path, params={"state": "all"}):
        try:
            is_open = pull["state"] == "open"
            is_merged = pull["merged_at"] is not None
            uses_branch = pull["head"]["label"] == head_label
            number = pull["number"]
        except (KeyError, TypeError) as error:
            raise FetchError(f"GitHub API returned a malformed pull request for {path}") from error
        # GitHub sends a null body for a pull request without a description.
        closes_issue = issue_reference in closing_references(pull.get("body") or "", repo)
        if (is_open or is_merged) and closes_issue:
            return number
        if is_open and uses_branch:
            return number
    return None


def _commits_ahead(client: GitHubClient, repo: str, main_sha: str, branch_sha: str) -> int:
    path = f"/repos/{repo}/compare/{main_sha}...{branch_sha}"
    comparison = get_json(client, path)
    ahead_by = comparison.get("ahead_by") if isinstance(comparison, dict) else None
    if not isinstance(ahead_by, int) or isinstance(ahead_by, bool) or ahead_by < 0:
        raise FetchError(f"GitHub API returned a malformed comparison for {path}")
    return ahead_by


def _remove_ready_label(client: GitHubClient, issue_path: str) -> None:
    try:
        client.delete(f"{issue_path}/labels/{READY_FOR_AGENT}")
    except FetchError as error:
        # Someone removed the label in the meantime: the state is already right.
        if error.status != HTTP_NOT_FOUND:
            raise


def _hand_to_person(client: GitHubClient, repo: str, issue: int, branch: str) -> None:
    """Comment, then swap the labels; the person is told before the state changes."""
    issue_path = f"/repos/{repo}/issues/{issue}"
    client.post(f"{issue_path}/comments", {"body": HANDOFF_COMMENT.format(branch=branch)})
    client.post(f"{issue_path}/labels", {"labels": [READY_FOR_HUMAN]})
    _remove_ready_label(client, issue_path)


def _release_ticket(client: GitHubClient, repo: str, issue: int, comment: str) -> None:
    """Tell the person, and always free the label: re-adding a present label fires no event."""
    issue_path = f"/repos/{repo}/issues/{issue}"
    try:
        client.post(f"{issue_path}/comments", {"body": comment})
    finally:
        _remove_ready_label(client, issue_path)


def _contract_texts(client: GitHubClient, repo: str, issue: int) -> list[str]:
    """The issue body and, as in the prompt's contract step, the latest Agent Brief.

    Both count, so a brief written later cannot erase a blocker the body declares.
    """
    issue_path = f"/repos/{repo}/issues/{issue}"
    ticket = get_json(client, issue_path)
    if not isinstance(ticket, dict) or "body" not in ticket:
        raise FetchError(f"GitHub API returned a malformed issue for {issue_path}")
    # GitHub sends a null body for an issue without a description.
    body = ticket["body"] or ""
    if not isinstance(body, str):
        raise FetchError(f"GitHub API returned a malformed issue for {issue_path}")
    briefs: list[str] = []
    for comment in paginate(client, f"{issue_path}/comments"):
        text = comment.get("body") if isinstance(comment, dict) else None
        if not isinstance(text, str):
            raise FetchError(f"GitHub API returned a malformed comment for {issue_path}")
        if text.startswith(AGENT_BRIEF_PREFIX):
            briefs.append(text)
    return [body, *briefs[-1:]]


def _closed_as_completed(issue: object, path: str) -> bool:
    """Only a completed issue counts: not planned still blocks, and a PR has no such state."""
    if not isinstance(issue, dict) or not isinstance(issue.get("state"), str):
        raise FetchError(f"GitHub API returned a malformed issue for {path}")
    return (
        issue["state"] == "closed"
        and issue.get("state_reason") == "completed"
        and "pull_request" not in issue
    )


def _belongs_to_repo(issue: dict, repo: str, path: str) -> bool:
    repository_url = issue.get("repository_url")
    if not isinstance(repository_url, str):
        raise FetchError(f"GitHub API returned a malformed issue for {path}")
    return repository_url.lower().endswith(f"/repos/{repo.lower()}")


def _declared_blocker_blocks(client: GitHubClient, repo: str, number: int) -> bool:
    """Fail closed: a deleted, missing or transferred blocker cannot be shown to be done."""
    path = f"/repos/{repo}/issues/{number}"
    try:
        blocker = get_json(client, path)
    except FetchError as error:
        if error.status in (HTTP_NOT_FOUND, HTTP_GONE):
            return True
        raise
    return not (_closed_as_completed(blocker, path) and _belongs_to_repo(blocker, repo, path))


def _find_blockers(client: GitHubClient, repo: str, issue: int) -> tuple[tuple[int, ...], int]:
    """Blocking issue numbers, and the blockers that cannot be named as one here.

    The contract's text and the native dependency edges both count: the ticket
    skills omit the "Blocked by" section when they set native edges. The edge
    list, unlike the issue's dependency summary, also returns closed blockers,
    so one closed as not planned is seen.
    """
    declared_numbers: set[int] = set()
    unresolved = 0
    for text in _contract_texts(client, repo, issue):
        declared = declared_blockers(text, repo)
        declared_numbers |= declared.numbers
        unresolved += declared.unresolved
    blocking = {
        number for number in declared_numbers if _declared_blocker_blocks(client, repo, number)
    }
    edges_path = f"/repos/{repo}/issues/{issue}/dependencies/blocked_by"
    for edge in paginate(client, edges_path):
        if _closed_as_completed(edge, edges_path):
            continue
        if _belongs_to_repo(edge, repo, edges_path):
            number = edge.get("number")
            if not isinstance(number, int):
                raise FetchError(f"GitHub API returned a malformed issue for {edges_path}")
            blocking.add(number)
        else:
            unresolved += 1
    return tuple(sorted(blocking)), unresolved


def _blocked_comment(blockers: tuple[int, ...], unresolved: int) -> str:
    reasons: list[str] = []
    if blockers:
        reasons.append("Blocked by " + ", ".join(f"#{number}" for number in blockers) + ".")
    if unresolved:
        reasons.append(
            f'{unresolved} "Blocked by" entries name no issue in this repository, so they '
            "count as blocking: write each one as `#<n>`, or remove it."
        )
    return BLOCKED_COMMENT.format(reason=" ".join(reasons))


def _single_page(
    client: ReadClient, path: str, items_key: str, params: dict[str, object] | None = None
) -> list:
    """The list under ``items_key``; more than one page would undercount, so it fails."""
    listing = get_json(client, path, params={**(params or {}), "per_page": PER_PAGE})
    items = listing.get(items_key) if isinstance(listing, dict) else None
    total_count = listing.get("total_count") if isinstance(listing, dict) else None
    if not isinstance(items, list) or not isinstance(total_count, int):
        raise FetchError(f"GitHub API returned an unexpected payload for {path}")
    if total_count > len(items):
        raise FetchError(f"GitHub API listed more items than one page holds for {path}")
    return items


def _implement_job_start(client: ReadClient, repo: str, run_id: int) -> datetime | None:
    """When the run's latest attempt started working, or None while it is not working.

    The job's status tells a working run from one whose job the workflow's `if`
    skipped, or one still queued.
    """
    path = f"/repos/{repo}/actions/runs/{run_id}/jobs"
    for job in _single_page(client, path, "jobs"):
        try:
            if job["name"] != IMPLEMENT_JOB:
                continue
            if job["status"] != "in_progress":
                return None
            started_at = datetime.fromisoformat(job["started_at"])
        except (KeyError, TypeError, ValueError) as error:
            raise FetchError(f"GitHub API returned a malformed job for {path}") from error
        if started_at.tzinfo is None:
            raise FetchError(f"GitHub API returned a malformed job for {path}")
        return started_at
    return None


def _runs_working_ahead(client: ReadClient, repo: str, run_id: int) -> int:
    """How many other working runs come before this one.

    Runs are ordered by (job start, run id), and only earlier runs count, so of
    two simultaneous starts exactly one sees the other and stops. The job start
    comes first because a re-run keeps its old run id: ordering by id alone would
    let a re-run ignore every newer run already working.
    """
    own_start = _implement_job_start(client, repo, run_id)
    if own_start is None:
        raise FetchError(f"GitHub API lists no working {IMPLEMENT_JOB} job for this run")
    runs_path = f"/repos/{repo}/actions/workflows/{IMPLEMENTER_WORKFLOW}/runs"
    runs_ahead = 0
    for run in _single_page(client, runs_path, "workflow_runs", {"status": "in_progress"}):
        other_id = run.get("id") if isinstance(run, dict) else None
        if not isinstance(other_id, int):
            raise FetchError(f"GitHub API returned a malformed run for {runs_path}")
        if other_id == run_id:
            continue
        other_start = _implement_job_start(client, repo, other_id)
        if other_start is not None and (other_start, other_id) < (own_start, run_id):
            runs_ahead += 1
    return runs_ahead


def claim_branch(
    client: GitHubClient, actions_client: ReadClient, repo: str, issue: int, run_id: int
) -> ClaimOutcome:
    """Decide this run's claim on ``agent/issue-<issue>`` and make the writes it needs."""
    branch = f"agent/issue-{issue}"
    holding_pull_request = _pull_request_holding_issue(client, repo, issue, branch)
    if holding_pull_request is not None:
        return ClaimOutcome(PR_EXISTS, branch, holding_pull_request)

    blockers, unresolved = _find_blockers(client, repo, issue)
    if blockers or unresolved:
        _release_ticket(client, repo, issue, _blocked_comment(blockers, unresolved))
        return ClaimOutcome(BLOCKED, branch, blockers=blockers, unresolved_blockers=unresolved)
    if _runs_working_ahead(actions_client, repo, run_id) >= MAX_WORKING_RUNS:
        _release_ticket(client, repo, issue, CAPACITY_COMMENT)
        return ClaimOutcome(AT_CAPACITY, branch)

    main_sha = _read_ref_sha(client, repo, MAIN_BRANCH)
    try:
        client.post(f"/repos/{repo}/git/refs", {"ref": f"refs/heads/{branch}", "sha": main_sha})
    except FetchError as create_error:
        if create_error.status != HTTP_UNPROCESSABLE:
            raise
        try:
            branch_sha = _read_ref_sha(client, repo, branch)
        except FetchError as read_error:
            # A 422 without the ref is some other rejection, not "already exists".
            if read_error.status == HTTP_NOT_FOUND:
                raise create_error from read_error
            raise
    else:
        return ClaimOutcome(CLAIMED, branch)

    if _commits_ahead(client, repo, main_sha, branch_sha) > 0:
        _hand_to_person(client, repo, issue, branch)
        return ClaimOutcome(NEEDS_HUMAN, branch)
    if branch_sha != main_sha:
        # Zero commits ahead makes this a fast-forward; force stays off regardless.
        client.patch(f"/repos/{repo}/git/refs/heads/{branch}", {"sha": main_sha, "force": False})
    return ClaimOutcome(RECLAIMED, branch)


def _required_token(variable: str) -> str:
    token = os.environ.get(variable)
    if not token:
        raise MissingTokenError(f"{variable} is not set")
    return token


def _workflow_run_id() -> int:
    value = os.environ.get("GITHUB_RUN_ID", "")
    if not value.isdecimal() or int(value) < 1:
        raise FetchError("GITHUB_RUN_ID is not a positive integer")
    return int(value)


def _repo_argument(value: str) -> str:
    if not REPO_PATTERN.fullmatch(value):
        raise argparse.ArgumentTypeError("must be OWNER/REPO")
    return value


def _issue_argument(value: str) -> int:
    if not value.isdecimal() or int(value) < 1:
        raise argparse.ArgumentTypeError("must be a positive integer")
    return int(value)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Claim agent/issue-<n> for one implementer run, or say why it must stop.",
        epilog=HELP_EPILOG,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--repo", required=True, type=_repo_argument, help="OWNER/REPO")
    parser.add_argument("--issue", required=True, type=_issue_argument, help="issue number")
    parser.add_argument(
        "--summary", required=True, type=Path, help="run summary file; written only on failure"
    )
    args = parser.parse_args(argv)

    try:
        client = GitHubClient(_required_token("GH_TOKEN"))
        actions_client = GitHubClient(_required_token(ACTIONS_TOKEN_VARIABLE))
        claim = claim_branch(client, actions_client, args.repo, args.issue, _workflow_run_id())
    except FetchError as error:
        reason = str(error)
        args.summary.write_text(f"{FAILED_PREFIX}: claim ({reason})\n", encoding="utf-8")
        print(json.dumps({"outcome": FAILED, "reason": reason}))
        return EXIT_FAILED
    print(json.dumps(asdict(claim)))
    return EXIT_CODES[claim.outcome]


if __name__ == "__main__":
    sys.exit(main())
