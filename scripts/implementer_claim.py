MAIN_BRANCH = "main"
HTTP_UNPROCESSABLE = 422

ACTIONS_TOKEN_VARIABLE = "ACTIONS_READ_TOKEN"  # noqa: S105 -- a variable name, not a value.

CLAIMED = "claimed"
RECLAIMED = "reclaimed"
PR_EXISTS = "pr-exists"
NEEDS_HUMAN = "needs-human"
NO_CONTRACT = "no-contract"
BLOCKED = "blocked"
AT_CAPACITY = "at-capacity"
FAILED = "failed"

EXIT_CONTINUE = 0
EXIT_FAILED = 1
EXIT_USAGE = 2
EXIT_PR_EXISTS = 3
EXIT_NEEDS_HUMAN = 4
EXIT_BLOCKED = 5
EXIT_AT_CAPACITY = 6
EXIT_NO_CONTRACT = 7
EXIT_CODES = {
    CLAIMED: EXIT_CONTINUE,
    RECLAIMED: EXIT_CONTINUE,
    PR_EXISTS: EXIT_PR_EXISTS,
    NEEDS_HUMAN: EXIT_NEEDS_HUMAN,
    BLOCKED: EXIT_BLOCKED,
    AT_CAPACITY: EXIT_AT_CAPACITY,
    NO_CONTRACT: EXIT_NO_CONTRACT,
}

HANDOFF_COMMENT = """\
> *This was generated by AI.*

The implementer did not start: branch `{branch}` has commits that are not on \
`main`, and no open pull request uses it. A run crashed after pushing, or a \
pull request from it was closed without merging. An implementer run never \
builds on such a branch, so this issue now waits for a person.

To continue the work, open a pull request from the branch. To start over, \
rescue what you need, delete the branch, and add `ready-for-agent` again.
"""

HELP_EPILOG = """\
stdout: JSON with outcome, branch, pull_request, blockers, unresolved_blockers ("reason" if failed).
--contract: written on claimed and reclaimed only; the text the run builds.
outcomes and exit codes:
  0 claimed      branch created at main
  0 reclaimed    branch existed with no commits of its own; moved to main
  3 pr-exists    an open or merged PR closes the issue, or an open PR uses the branch
  4 needs-human  branch has commits and no open PR; commented and set ready-for-human
  5 blocked      a declared blocker is not closed as completed; commented, kept the label (waits)
  6 at-capacity  another implementer run is working; commented, kept the label (waits)
                 with --queue-workflow '' both remove the label instead: no queue would start them
                 a queue that is no active workflow of --repo fails both (1) before the comment
  7 no-contract  no contract by a person with write access; commented, removed the label
  1 failed       any other API error; wrote "RUN FAILED: claim (<reason>)" to --summary
  2              usage error
An invalid --workflow-file, --branch-prefix, --queue-workflow or GITHUB_WORKFLOW_REF fails (1)
before any call. Only blocked and at-capacity read the --queue-workflow (implementer_waiting.py).
env: GH_TOKEN (the App token inside claude-code-action), ACTIONS_READ_TOKEN, GITHUB_RUN_ID,
     GITHUB_WORKFLOW_REF (names the caller's workflow file when run as a reusable workflow).

examples:
  implementer_claim.py --repo owner/repo --issue 42 --summary "$RUNNER_TEMP/run-summary.md" \\
      --contract "$RUNNER_TEMP/contract.md" --queue-workflow implementer-queue.yml
  implementer_claim.py --repo owner/repo --issue 42 --summary s.md --contract c.md \\
      --queue-workflow '' --workflow-file agent.yml --job-name implement \\
      --branch-prefix factory/issue-
  implementer_claim.py --help
"""


@dataclass(frozen=True)
class ClaimOutcome:
    outcome: str
    branch: str
    pull_request: int | None = None
    blockers: tuple[int, ...] = ()
    unresolved_blockers: int = 0
    # The text the run builds; main() writes it to --contract and keeps it off stdout.
    contract: str | None = None


def _read_ref_sha(client: GitHubClient, repo: str, branch: str) -> str:
    path = f"/repos/{repo}/git/ref/heads/{branch}"
    ref = get_json(client, path)
    try:
        sha = ref["object"]["sha"]
    except (KeyError, TypeError) as error:
        raise FetchError(f"GitHub API returned a malformed ref for {path}") from error
    if not isinstance(sha, str) or not sha:
        raise FetchError(f"GitHub API returned a malformed ref for {path}")
    return sha


def pull_request_holding_issue(
    client: GitHubClient, repo: str, issue: int, branch: str
) -> int | None:
    """The first open or merged PR that closes the issue, or an open PR on its branch."""
    path = f"/repos/{repo}/pulls"
    issue_reference = f"{repo.lower()}#{issue}"
    head_label = f"{repo.split('/')[0]}:{branch}"
    for pull in paginate(client, path, params={"state": "all"}):
        try:
            is_open = pull["state"] == "open"
            is_merged = pull["merged_at"] is not None
            uses_branch = pull["head"]["label"] == head_label
            number = pull["number"]
        except (KeyError, TypeError) as error:
            raise FetchError(f"GitHub API returned a malformed pull request for {path}") from error
        # GitHub sends a null body for a pull request without a description.
        closes_issue = issue_reference in closing_references(pull.get("body") or "", repo)
        if (is_open or is_merged) and closes_issue:
            return number
        if is_open and uses_branch:
            return number
    return None


def _commits_ahead(client: GitHubClient, repo: str, main_sha: str, branch_sha: str) -> int:
    path = f"/repos/{repo}/compare/{main_sha}...{branch_sha}"
    comparison = get_json(client, path)
    ahead_by = comparison.get("ahead_by") if isinstance(comparison, dict) else None
    if not isinstance(ahead_by, int) or isinstance(ahead_by, bool) or ahead_by < 0:
        raise FetchError(f"GitHub API returned a malformed comparison for {path}")
    return ahead_by


def remove_ready_label(client: GitHubClient, issue_path: str) -> None:
    try:
        client.delete(f"{issue_path}/labels/{READY_FOR_AGENT}")
    except FetchError as error:
        # Someone removed the label in the meantime: the state is already right.
        if error.status != HTTP_NOT_FOUND:
            raise


def _hand_to_person(client: GitHubClient, repo: str, issue: int, branch: str) -> None:
    """Comment, then swap the labels; the person is told before the state changes."""
    issue_path = f"/repos/{repo}/issues/{issue}"
    client.post(f"{issue_path}/comments", {"body": HANDOFF_COMMENT.format(branch=branch)})
    swap_to_human(client, issue_path)


def swap_to_human(client: GitHubClient, issue_path: str) -> None:
    """Replace `ready-for-agent` with `ready-for-human` on the issue at ``issue_path``."""
    client.post(f"{issue_path}/labels", {"labels": [READY_FOR_HUMAN]})
    remove_ready_label(client, issue_path)


def _comment(client: GitHubClient, repo: str, issue: int, comment: str) -> None:
    client.post(f"/repos/{repo}/issues/{issue}/comments", {"body": comment})


def _release_ticket(client: GitHubClient, repo: str, issue: int, comment: str) -> None:
    """Tell the person, and always free the label: re-adding a present label fires no event."""
    try:
        _comment(client, repo, issue, comment)
    finally:
        remove_ready_label(client, f"/repos/{repo}/issues/{issue}")


def _stop_at_gate(
    client: GitHubClient,
    actions_client: ReadClient,
    repo: str,
    issue: int,
    queue_workflow: str | None,
    comment_for: WaitingComment,
) -> None:
    """Park the ticket in the caller's queue, or release it when the caller has none.

    That one test picks both the comment and the label, so the text never promises
    a wait the label does not keep. The queue is read only here (implementer_waiting.py).
    """
    if queue_workflow is None:
        _release_ticket(client, repo, issue, comment_for(waits=False))
        return
    require_active_queue(actions_client, repo, queue_workflow)
    _comment(client, repo, issue, comment_for(waits=True))


def claim_branch(
    client: GitHubClient,
    actions_client: ReadClient,
    repo: str,
    issue: int,
    run_id: int,
    setup: ImplementerSetup = DEFAULT_SETUP,
    *,
    queue_workflow: str | None,
) -> ClaimOutcome:
    """Decide this run's claim on the issue's branch and make the writes it needs.

    ``queue_workflow`` is the caller's queue, or None: only with one do the
    blocked and at-capacity gates leave the ticket waiting, and only they read it.
    """
    branch = setup.branch(issue)
    holding_pull_request = pull_request_holding_issue(client, repo, issue, branch)
    if holding_pull_request is not None:
        return ClaimOutcome(PR_EXISTS, branch, holding_pull_request)

    ticket = read_ticket(client, repo, issue)
    contract = contract_text(ticket, issue)
    if contract is None:
        _release_ticket(client, repo, issue, NO_CONTRACT_COMMENT)
        return ClaimOutcome(NO_CONTRACT, branch)
    blockers = find_blockers(client, repo, issue, ticket)
    if blockers.block:
        # With a queue the ticket waits: implementer_queue.py starts it once unblocked.
        comment_for = partial(
            blocked_comment, blockers.numbers, blockers.unresolved, blockers.hidden
        )
        _stop_at_gate(client, actions_client, repo, issue, queue_workflow, comment_for)
        return ClaimOutcome(
            BLOCKED,
            branch,
            blockers=blockers.numbers,
            unresolved_blockers=blockers.unresolved + blockers.hidden,
        )
    if runs_working_ahead(actions_client, repo, run_id, setup) >= MAX_WORKING_RUNS:
        # With a queue the ticket waits: implementer_queue.py starts it when no run works.
        _stop_at_gate(client, actions_client, repo, issue, queue_workflow, capacity_comment)
        return ClaimOutcome(AT_CAPACITY, branch)

    main_sha = _read_ref_sha(client, repo, MAIN_BRANCH)
    try:
        client.post(f"/repos/{repo}/git/refs", {"ref": f"refs/heads/{branch}", "sha": main_sha})
    except FetchError as create_error:
        if create_error.status != HTTP_UNPROCESSABLE:
            raise
        try:
            branch_sha = _read_ref_sha(client, repo, branch)
        except FetchError as read_error:
            # A 422 without the ref is some other rejection, not "already exists".
            if read_error.status == HTTP_NOT_FOUND:
                raise create_error from read_error
            raise
    else:
        return ClaimOutcome(CLAIMED, branch, contract=contract)

    if _commits_ahead(client, repo, main_sha, branch_sha) > 0:
        _hand_to_person(client, repo, issue, branch)
        return ClaimOutcome(NEEDS_HUMAN, branch)
    if branch_sha != main_sha:
        # Zero commits ahead makes this a fast-forward; force stays off regardless.
        client.patch(f"/repos/{repo}/git/refs/heads/{branch}", {"sha": main_sha, "force": False})
    return ClaimOutcome(RECLAIMED, branch, contract=contract)


def _required_token(variable: str) -> str:
    token = os.environ.get(variable)
    if not token:
        raise MissingTokenError(f"{variable} is not set")
    return token


def _workflow_run_id() -> int:
    value = os.environ.get("GITHUB_RUN_ID", "")
    if not value.isdecimal() or int(value) < 1:
        raise FetchError("GITHUB_RUN_ID is not a positive integer")
    return int(value)


def _repo_argument(value: str) -> str:
    if not REPO_PATTERN.fullmatch(value):
        raise argparse.ArgumentTypeError("must be OWNER/REPO")
    return value


def _issue_argument(value: str) -> int:
    if not value.isdecimal() or int(value) < 1:
        raise argparse.ArgumentTypeError("must be a positive integer")
    return int(value)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Claim the issue's branch for one implementer run, or say why it must stop.",
        epilog=HELP_EPILOG,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--repo", required=True, type=_repo_argument, help="OWNER/REPO")
    parser.add_argument("--issue", required=True, type=_issue_argument, help="issue number")
    parser.add_argument(
        "--summary", required=True, type=Path, help="run summary file; written only on failure"
    )
    parser.add_argument(
        "--contract", required=True, type=Path, help="contract file; written when the run continues"
    )
    parser.add_argument(
        "--workflow-file",
        help=f"the run's workflow file name (default: from {WORKFLOW_REF_VARIABLE}, "
        f"else {IMPLEMENTER_WORKFLOW})",
    )
    parser.add_argument(
        "--job-name",
        default=IMPLEMENT_JOB,
        help="the implementer job; also matches '<caller job> / <name>' (default: %(default)s)",
    )
    parser.add_argument(
        "--branch-prefix",
        default=BRANCH_PREFIX,
        help="branch name before the issue number; ends in / or - (default: %(default)s)",
    )
    parser.add_argument(
        "--queue-workflow",
        required=True,
        help="the caller's queue workflow file, in which blocked and at-capacity tickets wait; "
        "'' for none, which removes their label",
    )
    args = parser.parse_args(argv)

    try:
        setup = ImplementerSetup(
            workflow_file(args.workflow_file), args.job_name, branch_prefix(args.branch_prefix)
        )
        queue = optional_workflow_file("--queue-workflow", args.queue_workflow)
        client = GitHubClient(_required_token("GH_TOKEN"))
        actions_client = GitHubClient(_required_token(ACTIONS_TOKEN_VARIABLE))
        claim = claim_branch(
            client,
            actions_client,
            args.repo,
            args.issue,
            _workflow_run_id(),
            setup,
            queue_workflow=queue,
        )
    except FetchError as error:
        reason = str(error)
        args.summary.write_text(f"{FAILED_PREFIX}: claim ({reason})\n", encoding="utf-8")
        print(json.dumps({"outcome": FAILED, "reason": reason}))
        print(f"implementer_claim.py: {reason}", file=sys.stderr)
        return EXIT_FAILED
    report = asdict(claim)
    contract = report.pop("contract")
    if contract is not None:
        args.contract.write_text(contract, encoding="utf-8")
    print(json.dumps(report))
    return EXIT_CODES[claim.outcome]


if __name__ == "__main__":
    sys.exit(main())
