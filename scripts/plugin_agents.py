#!/usr/bin/env python3
"""Render Claude plugin agents for Codex and OpenCode.

Usage: python3 scripts/plugin_agents.py RENDERER --source FILE --plugin-dir DIR --marker TEXT

Examples:
  python3 scripts/plugin_agents.py codex --source plugins/architecture/agents/coupling-analyst.md --plugin-dir plugins/architecture --marker '# generated by agents'
  python3 scripts/plugin_agents.py opencode --source plugins/architecture/agents/coupling-analyst.md --plugin-dir plugins/architecture --marker '# generated by agents'
"""

import argparse
import json
import sys
from pathlib import Path

TOOL_PERMISSIONS = {
    "Read": "read",
    "Grep": "grep",
    "Glob": "glob",
    "Bash": "shell",
    "Shell": "shell",
    "Edit": "edit",
    "Write": "edit",
    "WebFetch": "webfetch",
    "WebSearch": "websearch",
    "Task": "task",
    "AskUserQuestion": "question",
}


def parse_agent_source(source: Path):
    """Parse the repository's small, top-level agent frontmatter subset."""
    lines = source.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError("missing frontmatter")
    try:
        closing_line = lines.index("---", 1)
    except ValueError as error:
        raise ValueError("unclosed frontmatter") from error

    fields = {}
    active_key = None
    parts = []

    def store_field():
        if active_key is not None:
            fields[active_key] = " ".join(part.strip() for part in parts if part.strip())

    for line in lines[1:closing_line]:
        if line[:1] in (" ", "\t") and active_key is not None:
            parts.append(line)
            continue
        if not line.strip():
            continue
        store_field()
        key, separator, value = line.partition(":")
        if not separator or not key.strip():
            raise ValueError("invalid frontmatter line")
        active_key = key.strip()
        if value.strip() == ">-":
            value = ""
        parts = [value]
    store_field()

    try:
        name = fields["name"]
        description = fields["description"]
    except KeyError as error:
        raise ValueError(f"missing required frontmatter field: {error.args[0]}") from error
    if not name or not description:
        raise ValueError("name and description must be non-empty")

    body = "\n".join(lines[closing_line + 1 :]).strip()
    if not body:
        raise ValueError("empty agent body")
    return {"name": name, "description": description, "tools": fields.get("tools", "")}, body


def resolve_plugin_root(body: str, plugin_dir: str) -> str:
    return body.replace("${CLAUDE_PLUGIN_ROOT}", plugin_dir)


def render_codex(fields, body: str, plugin_dir: str, marker: str) -> str:
    body = resolve_plugin_root(body, plugin_dir) + "\n"
    body = body.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return (
        f"{marker}\n"
        f"name = {json.dumps(fields['name'])}\n"
        f"description = {json.dumps(fields['description'])}\n\n"
        f'developer_instructions = """\n{body}"""'
    )


def opencode_permissions(tools: str):
    permissions = {}
    for source_tool in tools.split(","):
        source_tool = source_tool.strip()
        if not source_tool:
            continue
        if source_tool not in TOOL_PERMISSIONS:
            raise ValueError(f"unsupported Claude tool in frontmatter: {source_tool}")
        permissions[TOOL_PERMISSIONS[source_tool]] = "allow"
    if "edit" not in permissions:
        permissions["edit"] = "deny"
    return permissions


def render_opencode(fields, body: str, plugin_dir: str, marker: str) -> str:
    description = json.dumps(fields["description"], ensure_ascii=False)
    lines = [
        "---",
        marker,
        f"description: {description}",
        "mode: subagent",
        "permission:",
    ]
    lines.extend(
        f"  {permission}: {action}"
        for permission, action in opencode_permissions(fields["tools"]).items()
    )
    body = resolve_plugin_root(body, plugin_dir)
    return "\n".join([*lines, "---", "", body]) + "\n"


def render_agent(renderer: str, source: Path, plugin_dir: str, marker: str) -> str:
    fields, body = parse_agent_source(source)
    if renderer == "codex":
        return render_codex(fields, body, plugin_dir, marker)
    return render_opencode(fields, body, plugin_dir, marker)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        usage="%(prog)s RENDERER --source FILE --plugin-dir DIR --marker TEXT",
        description="Render a plugin agent for the selected runtime.",
        epilog=(
            "Examples:\n"
            "  python3 scripts/plugin_agents.py codex --source plugins/architecture/agents/coupling-analyst.md --plugin-dir plugins/architecture --marker '# generated by agents'\n"
            "  python3 scripts/plugin_agents.py opencode --source plugins/architecture/agents/coupling-analyst.md --plugin-dir plugins/architecture --marker '# generated by agents'"
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("renderer", choices=("codex", "opencode"))
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--plugin-dir", required=True)
    parser.add_argument("--marker", required=True)
    args = parser.parse_args(argv)
    try:
        rendered = render_agent(args.renderer, args.source, args.plugin_dir, args.marker)
    except (OSError, UnicodeError, ValueError) as error:
        print(f"could not render plugin agent: {error}", file=sys.stderr)
        return 1
    sys.stdout.write(rendered)
    return 0


if __name__ == "__main__":
    sys.exit(main())
