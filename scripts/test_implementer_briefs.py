"""Which comment is the Agent Brief, and the blockers a brief declares."""

from __future__ import annotations

import implementer_claim
import pytest
from test_implementer_claim import ISSUE, REPO, FakeGitHub, claim
from test_implementer_intake_gates import assert_stopped_before_any_branch, blocker

# The format the triage skill posts (#768): the AI disclaimer, a blank line, then
# the heading. `text` stands where the brief's fields are, e.g. `**Blocked by:** #3`.
BRIEF_FORMAT = """\
> *This was generated by AI during triage.*

## Agent Brief

**Category:** bug
**Summary:** Fix the parser.
{text}

**Acceptance criteria:**
- [ ] The parser reads the new format.

**Out of scope:**
- Other parsers.

---
_Generated by [Claude Code](https://claude.ai/code)_
"""


def brief(text: str, author_association: str = "OWNER") -> dict:
    return {"body": BRIEF_FORMAT.format(text=text), "author_association": author_association}


def test_the_latest_brief_is_read_when_the_body_is_null():
    fake = FakeGitHub(
        issue_body=None,
        issue_comments=[brief("**Blocked by:** #3")],
        blocker_issues={3: blocker(state="open", state_reason=None)},
    )
    assert claim(fake).blockers == (3,)


def test_a_real_format_brief_naming_an_open_blocker_stops_the_run():
    fake = FakeGitHub(
        issue_comments=[brief("**Blocked by:** #3")],
        blocker_issues={3: blocker(state="open", state_reason=None)},
    )
    outcome = claim(fake)
    assert outcome.outcome == implementer_claim.BLOCKED
    assert outcome.blockers == (3,)
    assert "Blocked by #3." in assert_stopped_before_any_branch(fake)


def test_a_real_format_brief_naming_a_completed_blocker_lets_the_claim_proceed():
    fake = FakeGitHub(issue_comments=[brief("**Blocked by:** #3")], blocker_issues={3: blocker()})
    assert claim(fake).outcome == implementer_claim.CLAIMED


@pytest.mark.parametrize(
    "line",
    [
        f"Blocked by https://github.com/{REPO}/issues/3",
        "Blocked by https://github.com/FabianDistler/Agents/issues/3: start after it closes.",
        f"Blocked by <https://github.com/{REPO}/issues/3>",
    ],
    ids=["bare-url", "mixed-case-repo", "autolink"],
)
def test_a_blocked_by_url_of_this_repository_names_the_issue(line):
    fake = FakeGitHub(
        issue_comments=[brief(line)], blocker_issues={3: blocker(state="open", state_reason=None)}
    )
    outcome = claim(fake)
    assert outcome.outcome == implementer_claim.BLOCKED
    assert outcome.blockers == (3,)
    assert outcome.unresolved_blockers == 0


def test_a_completed_blocker_named_by_url_lets_the_claim_proceed():
    fake = FakeGitHub(
        issue_comments=[brief(f"Blocked by https://github.com/{REPO}/issues/3")],
        blocker_issues={3: blocker()},
    )
    assert claim(fake).outcome == implementer_claim.CLAIMED


@pytest.mark.parametrize(
    "line",
    [
        "Blocked by https://github.com/other/repo/issues/3",
        "Blocked by https://github.com/other/repo/pull/101: start only after it merges.",
        f"Blocked by https://github.com/{REPO}/pull/3",
    ],
    ids=["foreign-issue", "foreign-pull-request", "own-pull-request"],
)
def test_a_blocked_by_url_that_cannot_be_checked_fails_closed(line):
    fake = FakeGitHub(issue_comments=[brief(line)])
    outcome = claim(fake)
    assert outcome.outcome == implementer_claim.BLOCKED
    assert outcome.blockers == ()
    assert outcome.unresolved_blockers == 1
    comment = assert_stopped_before_any_branch(fake).replace("\n", " ")
    assert "pull request" in comment
    assert "remove it once it is done" in comment


def test_a_blocked_by_line_above_the_brief_heading_counts():
    """The shape of #675: the maintainer's note, then the brief, in one comment."""
    note = "Blocked by https://github.com/other/repo/pull/101: start only after it merges."
    body = f"{note}\n\n{BRIEF_FORMAT.format(text='')}"
    fake = FakeGitHub(issue_comments=[{"body": body, "author_association": "OWNER"}])
    assert claim(fake).unresolved_blockers == 1


def test_a_trusted_brief_inside_a_details_block_counts():
    inner = BRIEF_FORMAT.format(text="**Blocked by:** #3")
    body = f"Notes first.\n\n<details><summary>Brief</summary>\n\n{inner}\n</details>\n"
    fake = FakeGitHub(
        issue_comments=[{"body": body, "author_association": "COLLABORATOR"}],
        blocker_issues={3: blocker(state="open", state_reason=None)},
    )
    assert claim(fake).blockers == (3,)


def test_the_triage_bots_draft_brief_is_not_a_brief():
    """The bot posts as github-actions[bot] with association CONTRIBUTOR (#735, #748)."""
    draft = (
        "<!-- issue-triage-bot -->\n> *This was generated by AI during triage.*\n\n"
        "## Automated triage: `bug`, recommended `ready-for-agent`\n\n"
        "<details><summary>Draft agent brief</summary>\n\n"
        f"{BRIEF_FORMAT.format(text='**Blocked by:** #3')}\n</details>\n"
    )
    fake = FakeGitHub(
        issue_body="Build this.",
        issue_comments=[{"body": draft, "author_association": "CONTRIBUTOR"}],
        blocker_issues={3: blocker(state="open", state_reason=None)},
    )
    outcome = claim(fake)
    assert outcome.outcome == implementer_claim.CLAIMED
    assert outcome.contract is not None
    assert "Draft agent brief" not in outcome.contract


@pytest.mark.parametrize(
    "body",
    [
        "Use this format:\n\n```\n## Agent Brief\n**Blocked by:** #3\n```\n",
        "The heading `## Agent Brief` goes first. Blocked by: none\n",
        "<!--\n## Agent Brief\nBlocked by: #3\n-->\nSee the brief template.\n",
        "## Agent Briefing\n\nBlocked by: none\n",
    ],
    ids=["code-fence", "inline-code", "html-comment", "other-heading"],
)
def test_a_comment_that_only_mentions_the_heading_is_no_brief(body):
    fake = FakeGitHub(
        issue_body="Build this.",
        issue_comments=[
            brief("**Blocked by:** None"),
            {"body": body, "author_association": "OWNER"},
        ],
    )
    contract = claim(fake).contract
    assert contract is not None
    assert contract.startswith(f"Contract for issue #{ISSUE}. Source: the latest Agent Brief")
    assert "Fix the parser." in contract
    assert body not in contract


def test_a_comment_starting_with_the_heading_is_still_a_brief():
    fake = FakeGitHub(
        issue_comments=[
            {"body": "## Agent Brief\n\nBlocked by: #3", "author_association": "OWNER"}
        ],
        blocker_issues={3: blocker(state="open", state_reason=None)},
    )
    assert claim(fake).blockers == (3,)


def test_only_the_latest_brief_counts():
    fake = FakeGitHub(issue_comments=[brief("**Blocked by:** #3"), brief("**Blocked by:** None")])
    assert claim(fake).outcome == implementer_claim.CLAIMED


def test_a_brief_cannot_erase_a_blocker_the_body_declares():
    fake = FakeGitHub(
        issue_body="Blocked by: #3",
        issue_comments=[brief("**Blocked by:** None")],
        blocker_issues={3: blocker(state="open", state_reason=None)},
    )
    assert claim(fake).outcome == implementer_claim.BLOCKED


def test_ordinary_comments_declare_nothing():
    fake = FakeGitHub(issue_comments=[{"body": "Blocked by: #3"}])
    assert claim(fake).outcome == implementer_claim.CLAIMED
