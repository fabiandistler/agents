# The stop path, shared by both gates.


@pytest.mark.parametrize("gate", ["blocked", "at-capacity"])
def test_a_failed_comment_still_frees_the_label(gate):
    fake = stopped_fake(gate)
    fake.errors[("POST", COMMENTS)] = http_error(500, COMMENTS)
    with pytest.raises(pr_github_client.FetchError):
        claim(fake)
    assert [write[:2] for write in fake.writes] == [("DELETE", REMOVE_LABEL)]


@pytest.mark.parametrize("gate", ["blocked", "at-capacity"])
def test_a_label_already_gone_is_tolerated(gate):
    fake = stopped_fake(gate)
    fake.errors[("DELETE", REMOVE_LABEL)] = http_error(404, REMOVE_LABEL)
    assert claim(fake).outcome == gate


@pytest.mark.parametrize("gate", ["blocked", "at-capacity"])
def test_a_refused_label_removal_propagates(gate):
    fake = stopped_fake(gate)
    fake.errors[("DELETE", REMOVE_LABEL)] = http_error(403, REMOVE_LABEL)
    with pytest.raises(pr_github_client.FetchError) as caught:
        claim(fake)
    assert caught.value.status == 403


def stopped_fake(gate: str) -> FakeGitHub:
    if gate == "blocked":
        return FakeGitHub(issue_body="Blocked by: other/repo#3")
    return FakeGitHub(jobs={RUN_ID: [working_job()], 4999: [working_job(EARLIER)]})


# Gate 2: at-capacity and its tie-break.


def test_an_earlier_working_run_stops_this_one():
    fake = FakeGitHub(jobs={RUN_ID: [working_job()], 4999: [working_job(EARLIER)]})
    outcome = claim(fake)
    assert outcome.outcome == implementer_claim.AT_CAPACITY
    assert outcome.branch == BRANCH
    comment = assert_stopped_before_any_branch(fake)
    assert "another implementer run is working" in comment


def test_a_run_does_not_count_itself():
    assert claim(FakeGitHub()).outcome == implementer_claim.CLAIMED


def test_a_later_working_run_does_not_count():
    fake = FakeGitHub(jobs={RUN_ID: [working_job()], 5001: [working_job(LATER)]})
    assert claim(fake).outcome == implementer_claim.CLAIMED


@pytest.mark.parametrize(
    ("own_id", "other_id", "outcome"),
    [(5000, 5001, "claimed"), (5001, 5000, "at-capacity")],
    ids=["lower-id-proceeds", "higher-id-stops"],
)
def test_equal_starts_are_broken_by_the_run_id(own_id, other_id, outcome):
    fake = FakeGitHub(jobs={own_id: [working_job()], other_id: [working_job()]})
    client = cast(GitHubClient, fake)
    claimed = implementer_claim.claim_branch(client, client, REPO, ISSUE, own_id)
    assert claimed.outcome == outcome


@pytest.mark.parametrize(
    ("first_start", "second_start"),
    [(JOB_START, JOB_START), (EARLIER, LATER), (LATER, EARLIER)],
    ids=["same-second", "first-earlier", "second-earlier"],
)
def test_of_two_simultaneous_runs_exactly_one_proceeds(first_start, second_start):
    jobs = {5000: [working_job(first_start)], 5001: [working_job(second_start)]}
    outcomes = []
    for run_id in jobs:
        client = cast(GitHubClient, FakeGitHub(jobs=jobs))
        outcomes.append(implementer_claim.claim_branch(client, client, REPO, ISSUE, run_id).outcome)
    assert sorted(outcomes) == ["at-capacity", "claimed"]


def test_a_rerun_keeps_its_old_id_but_waits_for_the_newer_run_already_working():
    fake = FakeGitHub(jobs={100: [working_job(LATER)], RUN_ID: [working_job(EARLIER)]})
    client = cast(GitHubClient, fake)
    assert implementer_claim.claim_branch(client, client, REPO, ISSUE, 100).outcome == "at-capacity"


