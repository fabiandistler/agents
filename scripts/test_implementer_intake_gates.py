# The command line.


@pytest.mark.parametrize(
    ("gate", "expected_code"),
    [("blocked", 5), ("at-capacity", 6)],
)
def test_cli_reports_each_gate(monkeypatch, tmp_path, capsys, gate, expected_code):
    code, summary = run_cli(monkeypatch, tmp_path, stopped_fake(gate))
    printed = json.loads(capsys.readouterr().out)
    assert code == expected_code
    assert printed["outcome"] == gate
    assert printed["branch"] == BRANCH
    assert not summary.exists(), "only a failed claim writes the run summary"


def test_cli_reads_the_actions_api_with_the_job_token(monkeypatch, tmp_path, capsys):
    app_fake = FakeGitHub()
    job_fake = FakeGitHub(errors={("POST", CREATE_REF): AssertionError("job token wrote")})
    fakes = {"app-token": app_fake, "job-token": job_fake}
    monkeypatch.setenv("GH_TOKEN", "app-token")
    monkeypatch.setenv("ACTIONS_READ_TOKEN", "job-token")
    monkeypatch.setenv("GITHUB_RUN_ID", str(RUN_ID))
    monkeypatch.setattr(implementer_claim, "GitHubClient", lambda token: fakes[token])
    # A run list only the job token can read: the App token's route answers 403.
    app_fake.errors[("GET", RUNS)] = http_error(403, RUNS)
    code, _ = run_main(monkeypatch, tmp_path)
    assert code == implementer_claim.EXIT_CONTINUE
    assert json.loads(capsys.readouterr().out)["outcome"] == "claimed"
    assert job_fake.writes == []
    assert [write[:2] for write in app_fake.writes] == [("POST", CREATE_REF)]


def test_cli_turns_a_403_on_the_run_list_red(monkeypatch, tmp_path, capsys):
    fake = FakeGitHub(errors={("GET", RUNS): http_error(403, RUNS)})
    code, summary = run_cli(monkeypatch, tmp_path, fake)
    assert code == implementer_claim.EXIT_FAILED
    assert json.loads(capsys.readouterr().out)["outcome"] == "failed"
    assert summary.read_text(encoding="utf-8").startswith("RUN FAILED: claim (GitHub API returned")


@pytest.mark.parametrize("run_id", ["", "abc", "0", "-3"], ids=["empty", "text", "zero", "signed"])
def test_cli_rejects_a_bad_run_id(monkeypatch, tmp_path, capsys, run_id):
    monkeypatch.setattr(implementer_claim, "GitHubClient", lambda token: FakeGitHub())
    monkeypatch.setenv("GH_TOKEN", "app-token")
    monkeypatch.setenv("ACTIONS_READ_TOKEN", "job-token")
    monkeypatch.setenv("GITHUB_RUN_ID", run_id)
    code, _ = run_main(monkeypatch, tmp_path)
    assert code == implementer_claim.EXIT_FAILED
    assert json.loads(capsys.readouterr().out)["reason"] == (
        "GITHUB_RUN_ID is not a positive integer"
    )


def test_cli_without_the_actions_token_fails_the_claim(monkeypatch, tmp_path, capsys):
    monkeypatch.setenv("GH_TOKEN", "app-token")
    monkeypatch.delenv("ACTIONS_READ_TOKEN", raising=False)
    code, _ = run_main(monkeypatch, tmp_path)
    assert code == implementer_claim.EXIT_FAILED
    assert json.loads(capsys.readouterr().out)["reason"] == "ACTIONS_READ_TOKEN is not set"


def test_gates_keep_ticket_text_out_of_output_and_comments(monkeypatch, tmp_path, capsys):
    private_text = "Salary of Jane Doe"
    fake = FakeGitHub(issue_body=f"## Blocked by\n\n{private_text}\n")
    code, _ = run_cli(monkeypatch, tmp_path, fake)
    out = capsys.readouterr()
    assert code == implementer_claim.EXIT_BLOCKED
    assert private_text not in out.out + out.err
    assert private_text not in fake.writes[0][2]["body"]
