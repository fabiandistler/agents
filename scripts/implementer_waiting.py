"""What the claim tells a ticket it stops as `blocked` or `at-capacity`, and the queue check.

Both gates stop a run before any branch exists. A stopped ticket waits only
for a queue the caller has: the claim's --queue-workflow names it (the
`queue_workflow` input of factory-implementer.yml), and implementer_queue.py,
run from it, dispatches the next waiting ticket when a run ends or a blocker
closes. Such a ticket keeps `ready-for-agent`. Without a queue nothing would
ever start it (fabiandistler/repo-maintenance#205), so the claim removes the
label, since adding one the issue still carries fires no event, and the
comment says when to add it again. The claim's `_stop_at_gate` decides once
whether the ticket waits and passes that to the comment (`WaitingComment`),
so the text and the label never disagree.

Only a claim that parks a ticket reads the named queue, just before its
comment (`require_active_queue`). There a queue that is no active workflow of
the repository fails the claim before any write: a promise the claim cannot
keep is no fallback, so the Fix task sees a red run instead of a released
label. A claim that parks nothing does not read it: in a public repository
GitHub disables a scheduled workflow, as the queue is, after 60 days without
activity (https://docs.github.com/actions/using-workflows/disabling-and-enabling-a-workflow),
and that must not stop a run that has free capacity.

Standard library only.
"""

from __future__ import annotations

from typing import Protocol

from implementer_capacity import MAX_WORKING_RUNS
from pr_github_client import HTTP_NOT_FOUND, FetchError, ReadClient, get_json

# The one workflow state that runs: GitHub's REST description also lists
# deleted, disabled_fork, disabled_inactivity and disabled_manually.
ACTIVE = "active"

BLOCKED_COMMENT = """\
> *This was generated by AI.*

The implementer did not start. {reason}

A blocker counts as done only when it is closed as completed; closed as not \
planned still blocks. {next_step}
"""

BLOCKED_WAITS = (
    "This issue keeps `ready-for-agent` and waits in the implementer queue: once every "
    "blocker is done, the queue starts it when no other implementer run is working. To "
    "take it out of the queue, remove `ready-for-agent`."
)

CAPACITY_COMMENT = f"""\
> *This was generated by AI.*

The implementer did not start: another implementer run is working, and at most \
{MAX_WORKING_RUNS} may work at a time. {{next_step}}
"""

CAPACITY_WAITS = (
    "This issue keeps `ready-for-agent` and waits in the implementer queue, which starts "
    "it when no run is working; waiting issues start lowest number first. To take it out "
    "of the queue, remove `ready-for-agent`."
)

RELEASED = (
    "No implementer queue is set up here (the implementer caller passes no "
    "`queue_workflow`), so nothing starts this issue by itself. Add `ready-for-agent` "
    "again {restart}: the label is removed now, because adding one the issue still "
    "carries starts no run."
)


class WaitingComment(Protocol):
    """A stopped ticket's comment: ``capacity_comment``, or ``blocked_comment`` with blockers."""

    def __call__(self, *, waits: bool) -> str: ...


def require_active_queue(client: ReadClient, repo: str, queue_workflow: str) -> None:
    """Fail unless ``queue_workflow`` is an active workflow of ``repo``; reads Actions."""
    path = f"/repos/{repo}/actions/workflows/{queue_workflow}"
    try:
        workflow = get_json(client, path)
    except FetchError as error:
        if error.status == HTTP_NOT_FOUND:
            raise FetchError(
                f"--queue-workflow names no workflow of the repository ({error})", error.status
            ) from error
        raise
    state = workflow.get("state") if isinstance(workflow, dict) else None
    if not isinstance(state, str):
        raise FetchError(f"GitHub API returned a malformed workflow for {path}")
    if state != ACTIVE:
        raise FetchError(f"--queue-workflow names a workflow that is {state}: {path}")


def blocked_comment(blockers: tuple[int, ...], unresolved: int, *, waits: bool) -> str:
    reasons: list[str] = []
    if blockers:
        reasons.append("Blocked by " + ", ".join(f"#{number}" for number in blockers) + ".")
    if unresolved:
        reasons.append(
            f'{unresolved} "Blocked by" entries name no issue in this repository (a title, '
            "another repository's issue or a pull request), so they count as blocking: "
            "write each one as `#<n>`, or remove it once it is done."
        )
    next_step = BLOCKED_WAITS if waits else RELEASED.format(restart="once every blocker is done")
    return BLOCKED_COMMENT.format(reason=" ".join(reasons), next_step=next_step)


def capacity_comment(*, waits: bool) -> str:
    restart = "once the working run has ended"
    next_step = CAPACITY_WAITS if waits else RELEASED.format(restart=restart)
    return CAPACITY_COMMENT.format(next_step=next_step)
