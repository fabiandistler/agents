"""What the claim tells a ticket it stops as `blocked` or `at-capacity`.

Both gates stop a run before any branch exists. The ticket keeps
`ready-for-agent` and waits: implementer_queue.py dispatches the next waiting
ticket when a run ends or a blocker closes.

Standard library only.
"""

from __future__ import annotations

from implementer_capacity import MAX_WORKING_RUNS

BLOCKED_COMMENT = """\
> *This was generated by AI.*

The implementer did not start. {reason}

A blocker counts as done only when it is closed as completed; closed as not \
planned still blocks. This issue keeps `ready-for-agent` and waits in the \
implementer queue: once every blocker is done, the queue starts it when no other \
implementer run is working. To take it out of the queue, remove `ready-for-agent`.
"""

CAPACITY_COMMENT = f"""\
> *This was generated by AI.*

The implementer did not start: another implementer run is working, and at most \
{MAX_WORKING_RUNS} may work at a time. This issue keeps `ready-for-agent` and \
waits in the implementer queue, which starts it when no run is working; waiting \
issues start lowest number first. To take it out of the queue, remove \
`ready-for-agent`.
"""


def blocked_comment(blockers: tuple[int, ...], unresolved: int) -> str:
    reasons: list[str] = []
    if blockers:
        reasons.append("Blocked by " + ", ".join(f"#{number}" for number in blockers) + ".")
    if unresolved:
        reasons.append(
            f'{unresolved} "Blocked by" entries name no issue in this repository (a title, '
            "another repository's issue or a pull request), so they count as blocking: "
            "write each one as `#<n>`, or remove it once it is done."
        )
    return BLOCKED_COMMENT.format(reason=" ".join(reasons))
