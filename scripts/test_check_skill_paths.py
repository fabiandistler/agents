"""End-to-end tests for the dead-skill-path gate.

Each test builds a fixture repo tree, runs the gate's entry point against it
with --root, and asserts on the exit code and the reported lines.
"""

from pathlib import Path

import check_skill_paths


def run_gate(root: Path, capsys):
    code = check_skill_paths.main(["--root", str(root)])
    captured = capsys.readouterr()
    return code, captured.out, captured.err


def write(root: Path, rel: str, text: str = "x\n") -> Path:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def skill_md(body: str, name: str = "demo") -> str:
    return f"---\nname: {name}\ndescription: Demo.\n---\n\n{body}\n"


def test_existing_paths_in_prose_code_and_links_pass(tmp_path, capsys):
    write(tmp_path, "skills/demo/references/guide.md", "See [the rules](rules.md#top).\n")
    write(tmp_path, "skills/demo/references/rules.md", "Run `scripts/tool.py`.\n")
    write(tmp_path, "skills/demo/scripts/tool.py")
    write(tmp_path, "skills/demo/assets/template.md")
    body = (
        "Read [the guide](references/guide.md), then fill assets/template.md.\n\n"
        "```bash\npython3 scripts/tool.py --json\n```"
    )
    write(tmp_path, "skills/demo/SKILL.md", skill_md(body))

    code, out, err = run_gate(tmp_path, capsys)

    assert code == 0, err
    assert "skill paths ok (3 skill texts)" in out


def test_dead_paths_fail_with_file_and_line(tmp_path, capsys):
    write(tmp_path, "skills/demo/references/guide.md", "Next: [rules](rules.md).\n")
    body = (
        "Read `references/guide.md` and `references/gone.md`.\n\n"
        "```bash\npython3 scripts/missing.py\n```\n\n"
        "Fill [the template](assets/template.md)."
    )
    write(tmp_path, "skills/demo/SKILL.md", skill_md(body))

    code, _, err = run_gate(tmp_path, capsys)

    assert code == 1
    assert "skills/demo/SKILL.md:6: references/gone.md" in err
    assert "skills/demo/SKILL.md:9: scripts/missing.py" in err
    assert "skills/demo/SKILL.md:12: assets/template.md" in err
    assert "skills/demo/references/guide.md:1: rules.md" in err
    assert "SKILL.md:6: references/guide.md" not in err
    assert err.count("assets/template.md") == 1, "a dead link is reported once"


def test_router_member_copies_are_checked_once(tmp_path, capsys):
    write(tmp_path, "skills/demo/SKILL.md", skill_md("Run `scripts/missing.py`."))
    router = tmp_path / "skills/router/members"
    router.mkdir(parents=True)
    (router / "demo").symlink_to("../../demo")
    write(
        tmp_path,
        "skills/router/SKILL.md",
        skill_md("Open `members/demo/SKILL.md` or `members/<name>/SKILL.md`.", "router"),
    )

    code, _, err = run_gate(tmp_path, capsys)

    assert code == 1
    assert err.count("scripts/missing.py") == 1
    assert "members/" not in err


def test_urls_globs_and_foreign_prefixes_are_not_skill_paths(tmp_path, capsys):
    write(tmp_path, "skills/demo/scripts/test_tool.py")
    body = (
        "Paper: https://example.org/assets/papers/x.pdf and <https://example.org/references/y>.\n\n"
        "`scripts/test_*.py` are the tests. Repo layout: `skills/other/scripts/run.py`, "
        "`docs/references/z.md`."
    )
    write(tmp_path, "skills/demo/SKILL.md", skill_md(body))

    code, _, err = run_gate(tmp_path, capsys)

    assert code == 0, err


def test_a_glob_without_a_match_fails(tmp_path, capsys):
    write(tmp_path, "skills/demo/SKILL.md", skill_md("`scripts/test_*.py` are the tests."))

    code, _, err = run_gate(tmp_path, capsys)

    assert code == 1
    assert "scripts/test_*.py" in err


def test_path_resolves_in_a_skill_the_paragraph_names(tmp_path, capsys):
    write(tmp_path, "skills/helper/SKILL.md", skill_md("Helper.", "helper"))
    write(tmp_path, "skills/helper/scripts/lcom.py")
    body = (
        "Hand off to `helper`; its\n`scripts/lcom.py` measures cohesion.\n\n"
        "Elsewhere `scripts/lcom.py` is not ours."
    )
    write(tmp_path, "skills/demo/SKILL.md", skill_md(body))

    code, _, err = run_gate(tmp_path, capsys)

    assert code == 1
    assert "skills/demo/SKILL.md:9: scripts/lcom.py" in err
    assert ":7:" not in err


def test_repo_root_maintainer_paths_pass(tmp_path, capsys):
    write(tmp_path, "scripts/build_routers.py")
    write(tmp_path, "skills/demo/SKILL.md", skill_md("Generated by `scripts/build_routers.py`."))

    code, _, err = run_gate(tmp_path, capsys)

    assert code == 0, err


def test_unknown_argument_is_a_usage_error(capsys):
    assert check_skill_paths.main(["--bogus"]) == 2
    assert "usage:" in capsys.readouterr().err
