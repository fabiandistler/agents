#!/usr/bin/env python3
"""Pin the body of an audit finding a person has just released.

An `audit-finding` issue's body becomes the implementer's contract once a
person with write access adds `ready-for-agent` (ADR-0020). The Claude GitHub
App wrote that body and could edit it afterwards, and the REST API keeps no
body-edit time. So a model-free step, running as the workflow bot on the label
event, posts one comment holding the SHA-256 of the body at that moment.
``implementer_contract.body_is_trusted`` then accepts the body only while it
still hashes to the latest such marker posted after the latest release.

Run it with the workflow's GITHUB_TOKEN (``issues: write``): only markers by
``github-actions[bot]`` count. Standard library only. Errors name the API call,
never issue text.
"""

from __future__ import annotations

import argparse
import json
import os
import sys

from implementer_contract import (
    body_hash,
    is_audit_finding,
    is_pinned_since,
    latest_release_pin,
    person_release,
    release_marker,
)
from pr_cli import positive_int_argument, repo_argument
from pr_github_client import FetchError, GitHubClient, MissingTokenError, get_json

PINNED = "pinned"
ALREADY_PINNED = "already-pinned"
NOT_AUDIT_FINDING = "not-audit-finding"
NOT_RELEASED = "not-released"
FAILED = "failed"

EXIT_OK = 0
EXIT_FAILED = 1
EXIT_USAGE = 2  # argparse's own exit code

PIN_COMMENT = """\
{marker}
> *This was generated by a workflow, not by a model.*

A person with write access released this audit finding. The implementer \
builds the issue body only as it stands now: an edit to the body after this \
comment stops the run with `no-contract` until a person adds \
`ready-for-agent` again.
"""

HELP_EPILOG = f"""\
prints one JSON object: {{"outcome": ..., "sha256": ...}}
outcomes:
  {PINNED}             posted the release marker for the current body
  {ALREADY_PINNED}     the latest marker after the release already holds this body
  {NOT_AUDIT_FINDING}  the issue is closed, or not an App-filed audit finding
  {NOT_RELEASED}       no person with write access added the latest ready-for-agent
exit codes:
  {EXIT_OK}  one of the outcomes above
  {EXIT_FAILED}  a GitHub API call failed or GITHUB_TOKEN is unset ("outcome": "{FAILED}")
  {EXIT_USAGE}  usage error, such as an --issue below 1
environment:
  GITHUB_TOKEN  the workflow bot's token, with issues: write
"""


def pin_release(client: GitHubClient, repo: str, number: int) -> tuple[str, str | None]:
    """Post the release marker when a person released this open audit finding.

    Returns the outcome and the pinned hash. Running it twice posts one
    marker: the second run finds it. Two runs at the same moment can both post
    one, because the read and the post are not atomic; the latest marker
    decides, so the extra comment only clutters the issue.
    """
    issue_path = f"/repos/{repo}/issues/{number}"
    issue = get_json(client, issue_path)
    if not isinstance(issue, dict):
        raise FetchError(f"GitHub API returned a malformed issue for {issue_path}")
    if issue.get("state") != "open" or not is_audit_finding(issue):
        return NOT_AUDIT_FINDING, None
    release = person_release(client, repo, number)
    if release is None:
        return NOT_RELEASED, None
    digest = body_hash(issue)
    if is_pinned_since(latest_release_pin(client, repo, number), issue, release):
        return ALREADY_PINNED, digest
    comment = PIN_COMMENT.format(marker=release_marker(issue))
    client.post(f"{issue_path}/comments", {"body": comment})
    return PINNED, digest


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Pin the body of an audit finding a person released, as a marker comment.",
        epilog=HELP_EPILOG,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--repo", required=True, type=repo_argument, help="OWNER/REPO")
    parser.add_argument("--issue", required=True, type=positive_int_argument, help="issue number")
    args = parser.parse_args(argv)
    try:
        token = os.environ.get("GITHUB_TOKEN")
        if not token:
            raise MissingTokenError("GITHUB_TOKEN is not set")
        outcome, digest = pin_release(GitHubClient(token), args.repo, args.issue)
    except FetchError as error:
        print(json.dumps({"outcome": FAILED, "reason": str(error)}))
        print(f"audit_release_pin.py: {error}", file=sys.stderr)
        return EXIT_FAILED
    print(json.dumps({"outcome": outcome, "sha256": digest}))
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
